import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEnv } from 'vite';

const DEMO_PUBLISHER = '3940256099942544';
const DEMO_APP_IDS = {
  ios: `ca-app-pub-${DEMO_PUBLISHER}~1458002511`,
  android: `ca-app-pub-${DEMO_PUBLISHER}~3347511713`,
};

export function resolveNativeAdConfig(env) {
  const mode = env.VITE_ADS_MODE || 'test';
  if (!['test', 'production', 'off'].includes(mode)) throw new Error('VITE_ADS_MODE must be test, production or off.');
  const result = { mode };
  for (const platform of ['ios', 'android']) {
    const prefix = platform.toUpperCase();
    const appKey = `ADMOB_${prefix}_APP_ID`;
    const unitKey = `VITE_ADMOB_${prefix}_INTERSTITIAL_ID`;
    const appId = env[appKey] || (mode === 'production' ? '' : DEMO_APP_IDS[platform]);
    if (!/^ca-app-pub-\d{16}~\d{10}$/.test(appId)) throw new Error(`Set a valid ${appKey} in .env.native.local or the build environment.`);
    if (mode === 'production') {
      const unitId = env[unitKey] || '';
      if (appId.includes(DEMO_PUBLISHER) || !/^ca-app-pub-\d{16}\/\d{10}$/.test(unitId) || unitId.includes(DEMO_PUBLISHER)) {
        throw new Error(`Production requires live ${appKey} and ${unitKey}; Google demo IDs are not allowed.`);
      }
      if (appId.split('~')[0] !== unitId.split('/')[0]) throw new Error(`${appKey} and ${unitKey} must belong to the same AdMob publisher.`);
    }
    result[platform] = appId;
  }
  return result;
}

export async function configureNative(root = process.cwd(), env = { ...loadEnv('native', root, ''), ...process.env }) {
  // Validate every platform before writing either file. Values here are public
  // AdMob identifiers; credentials and signing keys do not belong in the app.
  const config = resolveNativeAdConfig(env);
  const files = [
    ['ios/App/Config/Ads.local.xcconfig', `// Generated by npm run native:configure. Do not commit.\nADMOB_APP_ID = ${config.ios}\nPIXELNOOK_ADS_MODE = ${config.mode}\n`],
    ['android/app/src/main/res/values/admob.local.xml', `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by npm run native:configure. Do not commit. -->\n<resources>\n    <string name="admob_app_id" translatable="false">${config.android}</string>\n    <string name="pixelnook_ads_mode" translatable="false">${config.mode}</string>\n</resources>\n`],
  ];
  for (const [relativePath, contents] of files) {
    const path = resolve(root, relativePath);
    await mkdir(dirname(path), { recursive: true });
    await writeFile(path, contents, { mode: 0o600 });
  }
  return config;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  try {
    const config = await configureNative();
    console.log(`Native AdMob configuration prepared (${config.mode}); no credentials copied into the app.`);
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
